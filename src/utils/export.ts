import { ChatSession } from '../types';

export function exportChatAsMarkdown(session: ChatSession): void {
  let md = `# ${session.title}\n\n`;
  md += `*Generated by স্বপন (Swapon) Multi-Model Hub on ${new Date(session.createdAt).toLocaleString()}*\n\n---\n\n`;

  for (const msg of session.messages) {
    const speaker = msg.role === 'user' ? '**User**' : `**Assistant (${msg.modelId})**`;
    const time = new Date(msg.timestamp).toLocaleTimeString();
    md += `### ${speaker} · *${time}*\n\n${msg.content}\n\n---\n\n`;
  }

  downloadFile(`${slugify(session.title)}.md`, md, 'text/markdown;charset=utf-8');
}

export function exportChatAsText(session: ChatSession): void {
  let text = `${session.title.toUpperCase()}\n`;
  text += `Date: ${new Date(session.createdAt).toLocaleString()}\n`;
  text += `========================================\n\n`;

  for (const msg of session.messages) {
    const speaker = msg.role === 'user' ? 'USER' : `ASSISTANT [${msg.modelId}]`;
    text += `[${speaker}]:\n${msg.content}\n\n----------------------------------------\n\n`;
  }

  downloadFile(`${slugify(session.title)}.txt`, text, 'text/plain;charset=utf-8');
}

export function exportAllSessionsAsJSON(sessions: ChatSession[]): void {
  const json = JSON.stringify(sessions, null, 2);
  downloadFile(`omniai-chat-backup-${new Date().toISOString().slice(0, 10)}.json`, json, 'application/json');
}

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .slice(0, 40) || 'chat-export';
}

function downloadFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
